"""失败测甲：重名站报文不得进邻站栏；两站落栏须可区分。

造两站同名夹具后灌入：当前写库按站名模糊解析，整批改写到邻站栏号，
本文件全部断言应在修复前见红。
"""
import pytest

from app.db import 连接
from app.services import 装载, 目录, 结栏, 夹具, 校验
from app.services import 栏号解析


def _造重名两站():
    """两个源键不同、名称完全相同的站点。"""
    conn = 连接()
    try:
        conn.execute("DELETE FROM 站点源 WHERE 源键 IN ('站-同名甲','站-同名乙')")
        conn.execute(
            "INSERT INTO 站点源(源键,名称,介质,区域,说明) VALUES (?,?,?,?,?)",
            ("站-同名甲", "重名监测站", "大气", "城区", "重名夹具甲"),
        )
        conn.execute(
            "INSERT INTO 站点源(源键,名称,介质,区域,说明) VALUES (?,?,?,?,?)",
            ("站-同名乙", "重名监测站", "大气", "近郊", "重名夹具乙"),
        )
        conn.commit()
    finally:
        conn.close()


def _开站名模糊策略():
    """复刻现状栏规：站名模糊策略 + 邻站栏号（串栏陷阱）。"""
    目录.改栏规({"解析策略": "站名", "邻站栏号": "B-邻站"})


def test_重名站各进各栏_不串邻站栏():
    _造重名两站()
    _开站名模糊策略()
    包 = 栏号解析.封包(备注="重名甲测")
    栏号解析.绑定站点栏("站-同名甲", "B-甲栏")
    栏号解析.绑定站点栏("站-同名乙", "B-乙栏")

    报告 = 装载.装一批(夹具.读取("重名站样例"))
    assert 报告["入栏"] == 2

    行 = {r["报文编号"]: r for r in 目录.缓冲列表()}
    甲 = 行["P-name-a-1"]
    乙 = 行["P-name-b-1"]
    # 硬约束：写路按站键精确解析，同名不得串栏
    assert 甲["栏号"] == "B-甲栏"
    assert 乙["栏号"] == "B-乙栏"
    assert 甲["栏号"] != 乙["栏号"]
    assert 甲["栏号"] != "B-邻站" and 乙["栏号"] != "B-邻站"
    # 每行须钉住解析真源指纹，写读同一站键
    assert 甲["解析指纹"] and 甲["解析指纹"] == 乙["解析指纹"]
    assert 甲["解析指纹"] == 栏号解析.当前指纹()


def test_重名站落栏可区分_结栏不混站():
    _造重名两站()
    _开站名模糊策略()
    栏号解析.封包()
    栏号解析.绑定站点栏("站-同名甲", "B-甲栏")
    栏号解析.绑定站点栏("站-同名乙", "B-乙栏")
    装载.装一批(夹具.读取("重名站样例"))

    结栏.结当前栏()  # 默认栏 B-demo，重名站不在此栏，不得空吃
    conn = 连接()
    try:
        组 = conn.execute(
            "SELECT 栏号,站点键 FROM 站点汇总账 ORDER BY 栏号,站点键"
        ).fetchall()
    finally:
        conn.close()
    落 = {(r["栏号"], r["站点键"]) for r in 组}
    assert ("B-甲栏", "站-同名甲") in 落
    assert ("B-乙栏", "站-同名乙") in 落
    assert ("B-邻站", "站-同名甲") not in 落
    assert ("B-邻站", "站-同名乙") not in 落
    # 同栏不得混入两个不同站键（跨站禁混）
    甲栏站 = {s for (b, s) in 落 if b == "B-甲栏"}
    乙栏站 = {s for (b, s) in 落 if b == "B-乙栏"}
    assert 甲栏站 == {"站-同名甲"}
    assert 乙栏站 == {"站-同名乙"}


def test_默认栏不被站名模糊整批劫持():
    _造重名两站()
    _开站名模糊策略()
    # 不做任何绑站：精确解析的默认落点是栏规当前栏号，而不是邻站栏号
    栏号解析.封包()
    装载.装一批(夹具.读取("重名站样例"))
    栏 = {r["栏号"] for r in 目录.缓冲列表()}
    assert 栏 == {目录.栏规()["当前栏号"]}
    assert "B-邻站" not in 栏


def test_解析真源卡可回读_拒站名模糊回刷():
    _造重名两站()
    卡 = 栏号解析.封包()
    assert 卡["解析真源"] == "站键精确"
    assert 卡["指纹"]
    映射 = {m["站点键"]: m["栏号"] for m in 栏号解析.站点栏映射()}
    assert 映射["站-同名甲"] == 映射["站-同名乙"] == 目录.栏规()["当前栏号"]
    # 模糊回刷必须被拒，不得改写物化包
    with pytest.raises((ValueError, RuntimeError)):
        栏号解析.按站名模糊回刷({"重名监测站": "B-劫持栏"})
    指纹后 = 栏号解析.当前指纹()
    assert 指纹后 == 卡["指纹"]
    assert "B-劫持栏" not in {m["栏号"] for m in 栏号解析.站点栏映射()}
    # 校验夹具本身仍合法
    assert 校验.校验批次(夹具.读取("重名站样例")) == []
