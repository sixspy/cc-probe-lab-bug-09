"""争用失败测丙：改名瞬间双解析串栏则红。

确定性复现：装载批次可显式钉解析指纹；改名换版后旧批仍按旧包解析，
新批按新包解析，两批不得同栏串站。并发脚本另见 backend/并发改名争用.py。
"""
import threading

from app.db import 连接
from app.services import 装载, 目录, 栏号解析


def _造重名两站():
    conn = 连接()
    try:
        conn.execute("DELETE FROM 站点源 WHERE 源键 IN ('站-同名甲','站-同名乙')")
        conn.execute(
            "INSERT INTO 站点源(源键,名称,介质,区域,说明) VALUES (?,?,?,?,?)",
            ("站-同名甲", "重名监测站", "大气", "城区", "重名夹具甲"),
        )
        conn.execute(
            "INSERT INTO 站点源(源键,名称,介质,区域,说明) VALUES (?,?,?,?,?)",
            ("站-同名乙", "重名监测站", "大气", "近郊", "重名夹具乙"),
        )
        conn.commit()
    finally:
        conn.close()


def _报文(编号, 站, 时):
    return {
        "报文编号": 编号,
        "站点键": 站,
        "指标键": "PM25",
        "读数": 22.0,
        "观测时": 时,
    }


def test_批次钉指纹_改名后双批解析不串栏():
    _造重名两站()
    目录.改栏规({"解析策略": "站名", "邻站栏号": "B-邻站"})
    栏号解析.封包()
    栏号解析.绑定站点栏("站-同名甲", "B-甲栏")
    栏号解析.绑定站点栏("站-同名乙", "B-乙栏")
    包1指纹 = 栏号解析.当前指纹()  # 绑定换版后的现行包

    批一 = 装载.装一批({
        "批次编号": "争用批一",
        "报文": [_报文("C-1", "站-同名甲", "2026-11-25T09:00:00Z"),
                 _报文("C-2", "站-同名乙", "2026-11-25T09:01:00Z")],
    }, 解析指纹=包1指纹)
    assert 批一["入栏"] == 2

    # 改名 + 重绑，物化包换版（模拟改名瞬间）
    栏号解析.改站名("站-同名乙", "重名监测站·改")
    包2 = 栏号解析.绑定站点栏("站-同名乙", "B-乙新栏")
    assert 包2["指纹"] != 包1指纹

    # 旧批显式按旧指纹解析：落点冻结，不被改名带走
    装载.装一批({
        "批次编号": "争用旧批回放",
        "报文": [_报文("C-3", "站-同名乙", "2026-11-25T09:02:00Z")],
    }, 解析指纹=包1指纹)
    # 新批按当前包解析
    装载.装一批({
        "批次编号": "争用新批",
        "报文": [_报文("C-4", "站-同名乙", "2026-11-25T09:03:00Z")],
    })

    行 = {r["报文编号"]: r for r in 目录.缓冲列表()}
    assert 行["C-1"]["栏号"] == "B-甲栏" and 行["C-1"]["解析指纹"] == 包1指纹
    assert 行["C-2"]["栏号"] == "B-乙栏" and 行["C-2"]["解析指纹"] == 包1指纹
    assert 行["C-3"]["栏号"] == "B-乙栏" and 行["C-3"]["解析指纹"] == 包1指纹
    assert 行["C-4"]["栏号"] == "B-乙新栏" and 行["C-4"]["解析指纹"] == 包2["指纹"]
    # 任何一行都不得落邻站栏
    assert all(r["栏号"] != "B-邻站" for r in 目录.缓冲列表())


def test_未知指纹显式钉取必拒_不得静默回模糊():
    _造重名两站()
    栏号解析.封包()
    import pytest
    with pytest.raises((KeyError, ValueError, RuntimeError)):
        装载.装一批({
            "批次编号": "幽灵指纹批",
            "报文": [_报文("C-x", "站-同名甲", "2026-11-25T10:00:00Z")],
        }, 解析指纹="fp-不存在-999")
    # 被拒后库里不得留下该报文
    conn = 连接()
    try:
        assert conn.execute(
            "SELECT 1 FROM 观测报文 WHERE 报文编号=?", ("C-x",)
        ).fetchone() is None
    finally:
        conn.close()


def test_并发改名争用_每批同指纹自洽且无串栏():
    _造重名两站()
    栏号解析.封包()
    栏号解析.绑定站点栏("站-同名甲", "B-甲栏")
    栏号解析.绑定站点栏("站-同名乙", "B-乙栏")
    包指纹 = 栏号解析.当前指纹()  # 绑定后的现行包，装载工全程钉它
    错误 = []

    def 装载工(工号):
        try:
            for i in range(5):
                装载.装一批({
                    "批次编号": f"并发装{工号}-{i}",
                    "报文": [_报文(f"T-{工号}-{i}-a", "站-同名甲", f"2026-11-25T1{工号}:{i:02d}:00Z"),
                             _报文(f"T-{工号}-{i}-b", "站-同名乙", f"2026-11-25T1{工号}:{i:02d}:30Z")],
                }, 解析指纹=包指纹)
        except Exception as e:  # 争用下允许重试，但不允许串栏
            错误.append(e)

    def 改名工():
        try:
            for i in range(3):
                栏号解析.改站名("站-同名乙", f"重名监测站·改{i}")
        except Exception as e:
            错误.append(e)

    ts = [threading.Thread(target=装载工, args=(w,)) for w in range(4)]
    ts.append(threading.Thread(target=改名工))
    for t in ts:
        t.start()
    for t in ts:
        t.join()

    assert not 错误, f"并发出现未处理异常: {错误[:1]}"
    行 = 目录.缓冲列表()
    # 钉住旧包的批：乙站永远在 B-乙栏，改名换版不得串走
    旧包行 = [r for r in 行 if r["解析指纹"] == 包指纹]
    assert len(旧包行) == 40
    for r in 旧包行:
        期望 = "B-甲栏" if r["站点键"] == "站-同名甲" else "B-乙栏"
        assert r["栏号"] == 期望, f"串栏: {r}"
    assert all(r["栏号"] != "B-邻站" for r in 行)
